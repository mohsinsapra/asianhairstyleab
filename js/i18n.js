let current = 'sv';

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'sv';
  try { localStorage.setItem('ahab-lang', current); } catch {}
  document.documentElement.lang = current;
  return current;
}

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem('ahab-lang'); } catch {}
  if (saved && STRINGS[saved]) return setLang(saved);
  // Anything that isn't a Swedish browser gets English.
  const nav = (navigator.language || 'sv').toLowerCase();
  return setLang(nav.startsWith('sv') ? 'sv' : 'en');
}

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.sv[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** Localised service name, falling back to Swedish. */
export function sname(service) {
  return service[current] || service.sv;
}

export function locale() {
  return LOCALES[current];
}
